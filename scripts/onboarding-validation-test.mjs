import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
process.chdir(fileURLToPath(new URL('../', import.meta.url)));
await mkdir('tmp/onboarding', { recursive: true });
const require = createRequire(process.cwd()+'/frontend/web-app/rommie-match/package.json');
await require('esbuild').build({ entryPoints:['frontend/web-app/rommie-match/src/features/onboarding/schemas/onboarding-schema.ts'], bundle:true, platform:'node', format:'cjs', outfile:'tmp/onboarding/schema.cjs' });
const futureDate = new Date(Date.now() + (7 * 24 + 7) * 3600000).toISOString().slice(0, 10);
const {onboardingDefaults:d,validateOnboardingStep:validate,profileToOnboarding:prefill}=require(process.cwd()+'/tmp/onboarding/schema.cjs');
assert.deepEqual(Object.keys(validate(1,d)).sort(),['age','city','employment','gender','name'].sort());
const personal={...d,name:'Nguyễn A',age:'22',gender:'Nam',employment:'Đang đi học',city:'TP.HCM'};
assert.ok(validate(1,personal).orgName);
