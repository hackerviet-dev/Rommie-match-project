assert.ok(validate(1,{...personal,age:'22.5'}).age);
assert.ok(validate(1,{...personal,age:'Infinity'}).age);
assert.equal(Object.keys(validate(2,d)).length,5);
assert.deepEqual(validate(2,{...d,sleep:'22h–0h',env:'Yên tĩnh',yn:{smoke:'Không',drink:'Không',pets:'Có'}}),{});
