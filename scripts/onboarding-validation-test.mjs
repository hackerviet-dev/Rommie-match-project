for (const employment of ['Đang đi học', 'Đang đi làm', 'Cả hai']) {
  assert.ok(validate(1,{...personal,employment,orgName:'   '}).orgName);
}
assert.ok(validate(1,{...personal,orgName:'a'.repeat(161)}).orgName);
assert.equal(validate(1,{...personal,orgName:'a'.repeat(160),bio:'a'.repeat(500)}).bio, undefined);
assert.ok(validate(1,{...personal,orgName:'RMIT',bio:'a'.repeat(501)}).bio);
assert.deepEqual(validate(1,{...personal,employment:'Khác',orgName:'',bio:''}),{});
assert.ok(validate(1,{...personal,name:'   ',age:'-1'}).name);
assert.ok(validate(1,{...personal,age:'22.5'}).age);
assert.ok(validate(1,{...personal,age:'Infinity'}).age);
for (const age of ['1', '17', '121', '18.5', '18.0', '']) assert.ok(validate(1,{...personal,age}).age);
for (const age of ['18', '120']) assert.equal(validate(1,{...personal,age,orgName:'RMIT'}).age, undefined);
assert.equal(Object.keys(validate(2,d)).length,5);
assert.deepEqual(validate(2,{...d,sleep:'22h–0h',env:'Yên tĩnh',yn:{smoke:'Không',drink:'Không',pets:'Có'}}),{});
assert.ok(validate(3,d).hasRoom);
assert.deepEqual(validate(3,{...d,hasRoom:'no'}),{});
assert.equal(Object.keys(validate(4,{...d,hasRoom:'no'})).length,3);
assert.deepEqual(validate(4,{...d,hasRoom:'no',distance:'2–5 km',roomType:'Phòng riêng',moveInDate:futureDate}),{});
assert.ok(validate(4,{...d,hasRoom:'no',moveInDate:'2026-02-30'}).moveInDate);
const room={...d,hasRoom:'yes',addr:'123 Nguyễn Huệ',district:'Quận 1',bedrooms:'2',area:'45',rent:'3.500.000',needed:'1',moveIn:futureDate,houseType:'Căn hộ'};
